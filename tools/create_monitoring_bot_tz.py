def register_fonts():
    pdfmetrics.registerFont(TTFont("DocFont", FONT_REGULAR))
    pdfmetrics.registerFont(TTFont("DocFont-Bold", FONT_BOLD))


def p(text, style):
    return Paragraph(text, style)


def bullets(items, style, bullet_type="1"):
    return ListFlowable(
        [ListItem(Paragraph(item, style), leftIndent=0) for item in items],
        bulletType=bullet_type,
        start="1",
        leftIndent=12,
        bulletFontName="DocFont",
        bulletFontSize=9,
    )


def checkbox_items(items, style):
    return ListFlowable(
        [ListItem(Paragraph(item, style), leftIndent=0) for item in items],
        bulletType="bullet",
        bulletFontName="DocFont",
        bulletFontSize=8,
        bulletIndent=0,
        leftIndent=14,
    )


def footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("DocFont", 8)
    canvas.setFillColor(colors.HexColor("#6b7280"))
    canvas.drawString(18 * mm, 12 * mm, "Техническое задание на бота мониторинга панелей Ipanel")
    canvas.drawRightString(192 * mm, 12 * mm, f"Стр. {doc.page}")
    canvas.restoreState()


def make_table(data, col_widths, style):
    if "TableHeaderRu" in style:
        normalized = []
        for row_index, row in enumerate(data):
            normalized_row = []
            for cell in row:
                if row_index == 0 and hasattr(cell, "getPlainText"):
                    normalized_row.append(Paragraph(cell.getPlainText(), style["TableHeaderRu"]))
                else:
                    normalized_row.append(cell)
            normalized.append(normalized_row)
        data = normalized
    table = Table(data, colWidths=col_widths, repeatRows=1)
    table.setStyle(
        TableStyle(
            [
                ("FONTNAME", (0, 0), (-1, 0), "DocFont-Bold"),
                ("FONTNAME", (0, 1), (-1, -1), "DocFont"),
                ("FONTSIZE", (0, 0), (-1, -1), 8),
                ("LEADING", (0, 0), (-1, -1), 10),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#111827")),
                ("BACKGROUND", (0, 1), (-1, -1), colors.HexColor("#ffffff")),
                ("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#d1d5db")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 5),
                ("RIGHTPADDING", (0, 0), (-1, -1), 5),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ]
        )
    )
    return table


